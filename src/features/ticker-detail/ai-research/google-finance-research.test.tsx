test('New chat resets the thread and restores the default ticker question', async () => {
  const user = userEvent.setup()
  mutateAsync.mockResolvedValueOnce(success)
  renderWithProviders(<GoogleFinanceResearch ticker="MSTR" />)
  await openChat(user)

  await user.click(screen.getByRole('button', { name: 'Submit' }))
  await within(screen.getByRole('dialog')).findByText('MSTR rally explained')

  await user.click(screen.getByRole('button', { name: 'New chat' }))

  expect(reset).toHaveBeenCalledTimes(1)
  expect(screen.queryByText('MSTR rally explained')).not.toBeInTheDocument()
  expect(screen.getByRole('textbox', { name: 'Google Finance question' })).toHaveValue(
    'Why is MSTR moving today?',
  )
  // The launcher card outside the (open, so aria-hidden) sheet drops its preview too.
  expect(
    screen.getByRole('button', { name: 'Ask Google Finance', hidden: true }),
  ).toBeInTheDocument()
})

