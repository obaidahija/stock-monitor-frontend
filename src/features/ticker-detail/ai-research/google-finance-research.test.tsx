import { cleanup, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, expect, test, vi } from 'vitest'
import { renderWithProviders } from '@/test/render'
import type { GoogleFinanceResearchOut } from '@/types/api'
import { GoogleFinanceResearch } from './google-finance-research'

const researchHook = vi.hoisted(() => vi.fn())

vi.mock('../hooks', () => ({
  useGoogleFinanceResearch: researchHook,
}))

const mutateAsync = vi.fn()
const reset = vi.fn()

const success: GoogleFinanceResearchOut = {
  ticker: 'MSTR',
  question: 'Why today?',
  answer_markdown: 'MSTR moved with **Bitcoin**.',
  sources: [
    {
      title: 'MSTR rally explained',
      publisher: 'Example News',
      url: 'https://example.com/mstr',
    },
  ],
  generated_at: '2026-09-04T13:00:00Z',
  caveat: 'Generated by Google Finance. Informational only.',
  source: {
    name: 'google_finance',
    ok: true,
    fetched_at: '2026-09-04T13:00:00Z',
    error: null,
    latency_ms: 8000,
  },
}

function setHookState(overrides: Record<string, unknown> = {}) {
  researchHook.mockReturnValue({
    mutateAsync,
    reset,
    error: null,
    isError: false,
    isPending: false,
    ...overrides,
  })
}

async function openChat(user: ReturnType<typeof userEvent.setup>) {
  await user.click(screen.getByRole('button', { name: /Ask Google Finance|Continue chat/ }))
}

beforeEach(() => {
  mutateAsync.mockReset()
  reset.mockReset()
  researchHook.mockReset()
  setHookState()
})

afterEach(cleanup)

test('shows a launcher button that opens the chat sheet', async () => {
  const user = userEvent.setup()
  renderWithProviders(<GoogleFinanceResearch ticker="MSTR" />)

  expect(screen.queryByRole('textbox', { name: 'Google Finance question' })).not.toBeInTheDocument()
  await openChat(user)

  expect(screen.getByRole('textbox', { name: 'Google Finance question' })).toBeInTheDocument()
  expect(screen.getByText('Ask about MSTR')).toBeInTheDocument()
})

test('submits edited text with no history yet', async () => {
  const user = userEvent.setup()
  mutateAsync.mockResolvedValue(success)
  renderWithProviders(<GoogleFinanceResearch ticker="MSTR" />)
  await openChat(user)

  const input = screen.getByRole('textbox', { name: 'Google Finance question' })
  expect(input).toHaveValue('Why is MSTR moving today?')
  await user.clear(input)
  await user.type(input, 'What changed after earnings?')
  await user.click(screen.getByRole('button', { name: 'Submit' }))

  expect(mutateAsync).toHaveBeenCalledWith({
    question: 'What changed after earnings?',
    history: [],
  })
})

test('disables submission and shows progress while research is pending', async () => {
  const user = userEvent.setup()
  setHookState({ isPending: true })
  renderWithProviders(<GoogleFinanceResearch ticker="MSTR" />)
  await openChat(user)

  expect(screen.getByRole('textbox', { name: 'Google Finance question' })).toBeDisabled()
  expect(screen.getByRole('button', { name: 'Submit' })).toBeDisabled()
})

test('renders markdown, attribution, and safe source links after asking', async () => {
  const user = userEvent.setup()
  mutateAsync.mockResolvedValue(success)
  renderWithProviders(<GoogleFinanceResearch ticker="MSTR" />)
  await openChat(user)

  await user.click(screen.getByRole('button', { name: 'Submit' }))

  const dialog = screen.getByRole('dialog')
  expect(await within(dialog).findByText('Bitcoin')).toBeInTheDocument()
  expect(within(dialog).getByText('Why today?')).toBeInTheDocument()
  expect(
    within(dialog).getByText('Generated by Google Finance. Informational only.'),
  ).toBeInTheDocument()
  const source = within(dialog).getByRole('link', { name: 'MSTR rally explained' })
  expect(source).toHaveAttribute('href', 'https://example.com/mstr')
  expect(source).toHaveAttribute('target', '_blank')
  expect(source).toHaveAttribute('rel', 'noopener noreferrer')
  expect(within(dialog).getByText('Example News')).toBeInTheDocument()
})

test('renders a degraded upstream turn inline and keeps the composer usable', async () => {
  const user = userEvent.setup()
  const degraded: GoogleFinanceResearchOut = {
    ...success,
    answer_markdown: null,
    sources: [],
    source: { ...success.source, ok: false, error: 'Google Finance page changed' },
  }
  mutateAsync.mockResolvedValue(degraded)
  renderWithProviders(<GoogleFinanceResearch ticker="NVDA" />)
  await openChat(user)

  await user.click(screen.getByRole('button', { name: 'Submit' }))

  const dialog = screen.getByRole('dialog')
  expect(await within(dialog).findByText('Google Finance page changed')).toBeInTheDocument()
  const input = screen.getByRole('textbox', { name: 'Google Finance question' })
  await user.type(input, 'Try another question')
  expect(input).toHaveValue('Try another question')
})

